'use client';

import React from 'react';

/**
 * Click-to-select bridge for the Page Builder canvas (Stage 06 Task 4 + 11).
 *
 * This component is rendered ONLY by `app/(public)/layout.tsx`, and only when
 * `isStaffDraftPreview()` is true — which requires both Next.js draft mode and
 * the `system.config` permission. A public visitor never receives this script.
 *
 * WHAT IT IS ALLOWED TO DO
 *
 *   - report which slot the operator clicked, to the parent frame;
 *   - outline a slot the parent names;
 *   - scroll a slot into view.
 *
 * WHAT IT CANNOT DO, BY CONSTRUCTION
 *
 *   - It performs no fetch, no server action and no database write, so a forged
 *     message cannot reach privileged code through it. The only effects a
 *     message can have are a CSS class and a scroll position.
 *   - It never assigns HTML. A slot id from a message is used solely as the
 *     value in `querySelector('[data-slot-id="..."]')` after being checked
 *     against a strict character allow-list, and the matched element must
 *     already exist in this document. Nothing from a message is inserted into
 *     the DOM, so there is no injection surface even if validation were bypassed.
 *
 * Messages are treated as untrusted input even though the canvas is same-origin:
 * same-origin only tells us the frame was served by us, not that the sender is
 * the Builder. Hence the checks in `isTrustedBuilderMessage` below.
 */

export const CANVAS_SOURCE = 'nfrguide-canvas';
export const BUILDER_SOURCE = 'nfrguide-builder';

/** Slot ids are generated by `crypto.randomUUID()` or `blk_<ts>_<rand>`. */
const SLOT_ID_PATTERN = /^[A-Za-z0-9_-]{1,64}$/;

export function isValidSlotId(value: unknown): value is string {
  return typeof value === 'string' && SLOT_ID_PATTERN.test(value);
}

export interface BuilderToCanvasMessage {
  source: typeof BUILDER_SOURCE;
  type: 'highlight' | 'ping';
  pageKey: string;
  slotId?: string | null;
}

/**
 * Every condition a parent message must satisfy. Exported so the test suite
 * asserts the real predicate rather than a re-implementation of it.
 *
 * @param allowedOrigin the exact origin the Builder must be served from —
 *        never a wildcard, and never derived from the message itself.
 */
export function isTrustedBuilderMessage(
  event: { origin: string; source: unknown; data: unknown },
  allowedOrigin: string,
  expectedParent: unknown,
  pageKey: string,
): event is { origin: string; source: unknown; data: BuilderToCanvasMessage } {
  // 1. Origin — explicit match against our own origin.
  if (event.origin !== allowedOrigin) return false;
  // 2. Source — must be the frame that embedded us, not a sibling or opener.
  //    `expectedParent` is null in a top-level document, where there is no
  //    legitimate sender at all, so this also rejects messages outside a canvas.
  if (expectedParent === null || event.source !== expectedParent) return false;
  // 3. Shape and provenance marker.
  const data = event.data;
  if (typeof data !== 'object' || data === null) return false;
  const msg = data as Partial<BuilderToCanvasMessage>;
  if (msg.source !== BUILDER_SOURCE) return false;
  if (msg.type !== 'highlight' && msg.type !== 'ping') return false;
  // 4. Editor context — a message meant for a different page is not for us.
  if (typeof msg.pageKey !== 'string' || msg.pageKey !== pageKey) return false;
  // 5. Slot identity — absent (clear selection) or a well-formed id.
  if (msg.slotId !== undefined && msg.slotId !== null && !isValidSlotId(msg.slotId)) return false;
  return true;
}

const SELECTED_CLASS = 'nfr-slot-selected';

