/** Query parameters the Builder canvas adds to the page it embeds. */
export const CANVAS_FLAG_PARAM = '_canvas';
export const CANVAS_PAGE_KEY_PARAM = '_pk';

/**
 * Whether this document is the Builder canvas, as opposed to an ordinary staff
 * draft preview.
 *
 * The distinction matters because the canvas suppresses navigation so a click
 * can mean "select". The standalone "Preview Draft" window must keep normal
 * browsing, so it must NOT get that behaviour — hence an explicit flag set only
 * by the embed path, rather than inferring intent from draft mode alone.
 */
export function readCanvasContext(search: string, isFramed: boolean): { active: boolean; pageKey: string } {
  const params = new URLSearchParams(search);
  const pageKey = params.get(CANVAS_PAGE_KEY_PARAM) ?? '';
  const active = isFramed && params.get(CANVAS_FLAG_PARAM) === '1' && pageKey.length > 0;
  return { active, pageKey };
}

export function BuilderCanvasBridge() {
  // Starts false so the server render and the first client render agree; the
  // effect turns it on only inside a real canvas.
  const [active, setActive] = React.useState(false);

  React.useEffect(() => {
    if (typeof window === 'undefined') return;

    const { active: isCanvas, pageKey } = readCanvasContext(window.location.search, window.parent !== window);
    if (!isCanvas) return;
    setActive(true);

    const allowedOrigin = window.location.origin;
    const parentFrame = window.parent;
    const doc = document;

    const clearSelection = () => {
      doc.querySelectorAll(`.${SELECTED_CLASS}`).forEach((el) => el.classList.remove(SELECTED_CLASS));
    };

    const markEmptySlots = () => {
      doc.querySelectorAll<HTMLElement>('[data-nfr-slot]').forEach((el) => {
        // A wrapper whose block rendered nothing has no element children and no
        // text. Marking it gives the operator a selectable target and an honest
        // explanation instead of an invisible gap (requirement 4.6).
        const isEmpty = el.children.length === 0 && (el.textContent ?? '').trim() === '';
        if (isEmpty && el.dataset.nfrUnrenderable !== '1') el.dataset.nfrEmpty = '1';
        else delete el.dataset.nfrEmpty;
      });
    };

    const select = (slotId: string | null | undefined, scroll: boolean) => {
      clearSelection();
      if (!slotId || !isValidSlotId(slotId)) return;
      // CSS.escape guards the selector even though the id is already
      // allow-listed: defence in depth, not a substitute for validation.
      const sel = typeof CSS !== 'undefined' && CSS.escape ? CSS.escape(slotId) : slotId;
      const el = doc.querySelector<HTMLElement>(`[data-slot-id="${sel}"]`);
      if (!el) return;
      el.classList.add(SELECTED_CLASS);
      if (scroll) el.scrollIntoView({ behavior: 'smooth', block: 'center' });
    };

    /**
     * Editor-selection mode: a click selects, it never navigates.
     *
     * Capture phase so a block's own handler cannot act first, and the default
     * is suppressed for every click in the canvas — not only on links — because
     * a block may carry a button, a form or a router push. Normal navigation
     * stays available through the Builder's explicit "Open page" action, which
     * opens the page in a new tab outside the canvas (requirement 4.8).
     */
    const onClickCapture = (e: MouseEvent) => {
      const target = e.target as Element | null;
      const wrapper = target?.closest?.('[data-slot-id]') as HTMLElement | null;
      e.preventDefault();
      e.stopPropagation();
      const slotId = wrapper?.dataset.slotId;
      select(slotId ?? null, false);
      parentFrame.postMessage(
        { source: CANVAS_SOURCE, type: 'slot-selected', pageKey, slotId: slotId ?? null },
        allowedOrigin, // explicit target origin — never '*'
      );
    };

    const onSubmitCapture = (e: Event) => {
      e.preventDefault();
      e.stopPropagation();
    };

    const onMessage = (e: MessageEvent) => {
      if (!isTrustedBuilderMessage(e, allowedOrigin, parentFrame, pageKey)) return;
      const msg = e.data as BuilderToCanvasMessage;
      if (msg.type === 'highlight') select(msg.slotId ?? null, true);
    };

    doc.addEventListener('click', onClickCapture, true);
    doc.addEventListener('submit', onSubmitCapture, true);
    window.addEventListener('message', onMessage);
    markEmptySlots();

    parentFrame.postMessage({ source: CANVAS_SOURCE, type: 'ready', pageKey }, allowedOrigin);

    return () => {
      doc.removeEventListener('click', onClickCapture, true);
      doc.removeEventListener('submit', onSubmitCapture, true);
      window.removeEventListener('message', onMessage);
      clearSelection();
    };
  }, []);

  if (!active) return null;
  // eslint-disable-next-line react/no-danger -- a module-level authored constant,
  // never message or user input; this is the documented way to ship canvas CSS.
  return <style data-nfr-canvas-styles="" dangerouslySetInnerHTML={{ __html: CANVAS_STYLES }} />;
}

export default BuilderCanvasBridge;
